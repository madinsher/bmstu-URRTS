def load_map(text):
    """Карта из строк: '#' — стеллаж, '.' — проход."""
    rows = [r for r in text.strip("\n").split("\n")]
    return np.array([[ch == "#" for ch in r] for r in rows], dtype=bool)


def successors(grid, cell):
    """Допустимые клетки следующего момента (включая ожидание)."""
    out = []
    for dr, dc in MOVES:
        r, c = cell[0] + dr, cell[1] + dc
        if 0 <= r < grid.shape[0] and 0 <= c < grid.shape[1] and not grid[r, c]:
            out.append((r, c))
    return out


