def execute(paths, delay_prob, rng, max_ticks=10000):
    """Исполнение по графу зависимостей: на каждом такте агент пытается выполнить
    следующее действие, если все зависимости выполнены и он не «задержан»
    (с вероятностью delay_prob — проскальзывание, занятый манипулятор и т. п.).
    Возвращает (такты до завершения, журнал позиций по тактам)."""
    actions, deps = action_dependencies(paths)
    nxt = [0] * len(paths)
    pos = [p[0] for p in paths]
    done = set()
    log = [list(pos)]
    for tick in range(1, max_ticks + 1):
        if all(nxt[i] == len(actions[i]) for i in range(len(paths))):
            return tick - 1, log
        ready = []
        for i in range(len(paths)):
            if nxt[i] == len(actions[i]) or rng.random() < delay_prob:
                continue
            if deps[(i, nxt[i])] <= done:
                ready.append(i)
        for i in ready:
            _, w, _ = actions[i][nxt[i]]
            pos[i] = w
            done.add((i, nxt[i]))
            nxt[i] += 1
        log.append(list(pos))
    return None, log


def execute_naive(paths, delay_prob, rng, max_ticks=10000):
    """Исполнение «по часам» — для сравнения. Действие k агента выполняется на такте,
    не раньше его планового момента прибытия t_k; задержанный агент выполняет его
    позже и затем догоняет расписание (следующие действия — снова по плановым моментам,
    но не раньше, чем через такт после предыдущего). Координации нет.
    Возвращает число пар «два робота в одной клетке» по всем тактам."""
    actions = [compress(p) for p in paths]
    nxt = [0] * len(paths)
    pos = [p[0] for p in paths]
    collisions = 0
    for tick in range(1, max_ticks + 1):
        if all(nxt[i] == len(actions[i]) for i in range(len(paths))):
            break
        for i in range(len(paths)):
            if nxt[i] < len(actions[i]) and tick >= actions[i][nxt[i]][2] and rng.random() >= delay_prob:
                pos[i] = actions[i][nxt[i]][1]
                nxt[i] += 1
        collisions += len(pos) - len(set(pos))
    return collisions


